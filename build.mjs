/* node build.mjs          → dist/ (load it unpacked) and keepessence-extension-<version>.zip
   node build.mjs --test   → dist-test/: the same code plus what an automated browser needs
                             (see tests/e2e). Never packaged.
   node build.mjs --gen    → only src/generated/contract.ts, from contract/openapi.yaml */
import { build } from 'esbuild';
import { cpSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { crc32, deflateRawSync } from 'node:zlib';
import { parse } from 'yaml';

const root = dirname(fileURLToPath(import.meta.url));
const at = (...p) => join(root, ...p);
const args = new Set(process.argv.slice(2));
const test = args.has('--test');

/* ---------------------------------------------------------------- from the contract */

/* The sentences and the two numbers a browser needs before it has ever reached a core.
   Generated, never hand-written: the contract stays the only copy (rule C3). The secret-like
   patterns are deliberately not here; they only come from GET /v1/meta. */
function generate() {
  const contract = parse(readFileSync(at('contract/openapi.yaml'), 'utf8'));
  const messages = {};
  for (const [key, value] of Object.entries(contract['x-shared-rules'].save_messages)) {
    if (value && typeof value === 'object' && typeof value.zh === 'string' && typeof value.en === 'string') messages[key] = { zh: value.zh, en: value.en };
  }
  const limits = { image_long_edge_px: contract['x-limits'].image_long_edge_px, asset_max_bytes: contract['x-limits'].asset_max_bytes };
  mkdirSync(at('src/generated'), { recursive: true });
  writeFileSync(
    at('src/generated/contract.ts'),
    `/* Generated by build.mjs from contract/openapi.yaml (version ${contract.info.version}). Do not edit. */\n` +
      `import type { Bilingual } from '../lib/types.ts';\n\n` +
      `export const CONTRACT_VERSION = ${JSON.stringify(contract.info.version)};\n\n` +
      `export const SAVE_MESSAGES: Record<string, Bilingual> = ${JSON.stringify(messages, null, 2)};\n\n` +
      `export const LIMITS = ${JSON.stringify(limits, null, 2)};\n`,
  );
}

/* ---------------------------------------------------------------- zip (no dependency) */

function files(dir, base = dir) {
  return readdirSync(dir).sort().flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? files(p, base) : [relative(base, p).split('\\').join('/')];
  });
}

function zip(dir, out) {
  const parts = [];
  const central = [];
  let offset = 0;
  for (const name of files(dir)) {
    const data = readFileSync(join(dir, name));
    const packed = deflateRawSync(data, { level: 9 });
    const nameBytes = Buffer.from(name, 'utf8');
    const head = Buffer.alloc(30);
    head.writeUInt32LE(0x04034b50, 0);
    head.writeUInt16LE(20, 4);
    head.writeUInt16LE(0x0800, 6); // names are UTF-8
    head.writeUInt16LE(8, 8);
    head.writeUInt16LE(0, 10); // a fixed time: the same sources give the same zip
    head.writeUInt16LE(0x21, 12);
    head.writeUInt32LE(crc32(data), 14);
    head.writeUInt32LE(packed.length, 18);
    head.writeUInt32LE(data.length, 22);
    head.writeUInt16LE(nameBytes.length, 26);
    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50, 0);
    entry.writeUInt16LE(20, 4);
    head.copy(entry, 6, 4, 30); // version needed … name length
    entry.writeUInt32LE(offset, 42);
    parts.push(head, nameBytes, packed);
    central.push(entry, nameBytes);
    offset += 30 + nameBytes.length + packed.length;
  }
  const dirBytes = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(central.length / 2, 8);
  end.writeUInt16LE(central.length / 2, 10);
  end.writeUInt32LE(dirBytes.length, 12);
  end.writeUInt32LE(offset, 16);
  writeFileSync(out, Buffer.concat([...parts, dirBytes, end]));
}

/* ---------------------------------------------------------------- build */

generate();
if (args.has('--gen')) process.exit(0);

/* a test build never talks to the real service: its address is a core on this machine */
const server = test ? (process.env.KE_CORE_URL || 'http://127.0.0.1:8794').replace(/\/+$/, '') : 'https://keepessence.app';
if (test && !/^http:\/\/127\.0\.0\.1(:\d+)?$/.test(server)) throw new Error('a test build only talks to http://127.0.0.1:<port>');
const out = at(test ? 'dist-test' : 'dist');
rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

await build({
  entryPoints: [at('src/background.ts'), at('src/options.ts')],
  outdir: out,
  bundle: true,
  format: 'esm',
  target: 'chrome116',
  minify: false, // page.ts functions are sent into pages by their source text: keep them as written
  legalComments: 'none',
  define: { KE_DEFAULT_SERVER: JSON.stringify(server) },
  dropLabels: test ? [] : ['TEST'], // the test hooks at the end of background.ts
  logLevel: 'warning',
});

const manifest = JSON.parse(readFileSync(at('src/manifest.json'), 'utf8'));
/* A release is built as the version it is about to get: dev/release-zip.mjs passes it in KE_VERSION,
   because semantic-release only works that version out when the release run is under way and
   package.json stays at 1.0.0. Any other build keeps package.json's version. */
const version = process.env.KE_VERSION || JSON.parse(readFileSync(at('package.json'), 'utf8')).version;
if (!/^\d+\.\d+\.\d+$/.test(version)) throw new Error(`the version "${version}" is not x.y.z, which is what a release gets`);
manifest.version = version;
if (test) {
  /* An automated browser cannot press the toolbar button, so there is no activeTab grant, and it
     cannot answer the browser's permission question. The test build may therefore touch the
     test site and reach a core on this machine from the start. */
  manifest.host_permissions.push('http://127.0.0.1/*');
  manifest.name = 'KeepEssence (test build)';
}
writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
for (const f of ['options.html', 'options.css', 'tokens.css']) cpSync(at('src', f), join(out, f));
cpSync(at('src/icons'), join(out, 'icons'), { recursive: true });
cpSync(at('src/_locales'), join(out, '_locales'), { recursive: true });
cpSync(at('src/_locales/zh_CN'), join(out, '_locales/zh_TW'), { recursive: true }); // zh_TW would otherwise fall back to English

/* KE_LANG=zh node build.mjs --test: a Mac browser takes its language from the system and an
   automated one cannot be told otherwise, so the Chinese catalogue is put where the browser looks */
if (test && /^zh/i.test(process.env.KE_LANG || '')) cpSync(at('src/_locales/zh_CN'), join(out, '_locales/en'), { recursive: true });

/* the two locales must have the same keys, or one language shows a raw key */
const keys = (l) => Object.keys(JSON.parse(readFileSync(at('src/_locales', l, 'messages.json'), 'utf8'))).sort().join();
if (keys('zh_CN') !== keys('en')) throw new Error('_locales: zh_CN and en do not have the same keys');

if (!test) {
  const name = `keepessence-extension-${version}.zip`;
  zip(out, at(name));
  console.log(`dist/ and ${name}`);
} else console.log('dist-test/');
